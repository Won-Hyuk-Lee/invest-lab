from typing import Protocol


class Broker(Protocol):
    def account(self) -> dict: ...
    def quote(self, symbol: str) -> dict: ...
    def capacity(self, symbol: str, price: str, order_type: str) -> dict: ...
    def place_order(self, payload: dict) -> dict: ...
    def cancel_order(self, order: dict, quantity: int, price: str | None = None) -> dict: ...
    def orders(self, start: str, end: str) -> list[dict]: ...


class ExecutionRepository(Protocol):
    mode: str
    account_id: str

    def create_intent(self, payload: dict, at: str, context: dict) -> dict: ...
    def get_order(self, order_id: str) -> dict: ...
    def find_intent(self, client_id: str) -> dict | None: ...
    def list_orders(self, **filters) -> dict: ...
    def transition(
        self, order_id: str, expected: set[str], state: str, at: str, **values
    ) -> dict: ...
    def document(self, kind: str, key: str = "latest") -> dict | None: ...
    def put_document(self, kind: str, value: dict, key: str = "latest") -> None: ...
    def execution_lock(self): ...
    def command(self, command_id: str, payload: dict, at: str) -> tuple[dict, bool]: ...
    def finish_command(self, command_id: str, state: str, result: dict) -> None: ...
