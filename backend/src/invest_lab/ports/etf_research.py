"""Ports for a separate ETF laboratory; no trading or existing account-store methods."""

from typing import Protocol


class EtfDataSource(Protocol):
    def collect(self, symbols: list[str], start: str, end: str) -> dict: ...


class EtfResearchStore(Protocol):
    def save_dataset(self, dataset: dict) -> str: ...
    def load_dataset(self, dataset_id: str) -> dict: ...
    def save_run(self, result: dict) -> str: ...
    def list_runs(self) -> list[dict]: ...
    def load_run(self, run_id: str) -> dict: ...
