"""Storage/estimator contracts used by the research application."""

from typing import Protocol


class ResearchRepository(Protocol):
    def save_dataset(self, dataset: dict) -> dict: ...
    def get_dataset(self, dataset_id: str) -> dict: ...
    def list_datasets(self) -> list[dict]: ...
    def save_experiment(self, experiment: dict) -> dict: ...
    def get_experiment(self, experiment_id: str) -> dict: ...
    def list_experiments(self) -> list[dict]: ...
    def save_model(self, model: dict) -> dict: ...
    def list_models(self) -> list[dict]: ...
    def export_dataset(self, dataset_id: str) -> dict: ...


class ResearchLearner(Protocol):
    def train(self, rows: list[dict], parameters: dict) -> dict: ...
    def predict(self, artifact: dict, features: list[dict]) -> list[float]: ...
