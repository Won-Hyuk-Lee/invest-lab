import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { format, resolveConfig } from "prettier";

// The CI exporter supplies a file; local development can use an explicit API URL.
const source = process.env.INVEST_OPENAPI_PATH;
const endpoint =
  process.env.INVEST_OPENAPI_URL ?? "http://127.0.0.1:8000/openapi.json";
const schema = source
  ? JSON.parse(await readFile(source, "utf8"))
  : await (async () => {
      const response = await fetch(endpoint, {
        signal: AbortSignal.timeout(15_000),
      });
      if (!response.ok)
        throw new Error(`OpenAPI returned HTTP ${response.status}`);
      return response.json();
    })();
const output = new URL("../src/api.generated.ts", import.meta.url);
const config = await resolveConfig(fileURLToPath(output));
const generated = await format(
  "// Generated by npm run api:generate. Do not edit by hand.\n" +
    astToString(await openapiTS(schema, { alphabetize: true })),
  { ...config, parser: "typescript", endOfLine: "lf" },
);
if (process.argv.includes("--check")) {
  const existing = await readFile(output, "utf8").catch(() => "");
  if (existing.replaceAll("\r\n", "\n") !== generated) {
    console.error(
      "API contract drift detected. Regenerate with npm run api:generate and review the changes.",
    );
    process.exitCode = 1;
  } else console.log("API contract matches the backend OpenAPI schema.");
} else {
  await writeFile(output, generated, "utf8");
  console.log(
    "Generated src/api.generated.ts from the backend OpenAPI schema.",
  );
}
